// Rebuild static image variants before publishing; originals are kept for editing.
const fs = require("node:fs/promises");
const path = require("node:path");
const { createHash } = require("node:crypto");
const sharp = require("sharp");

const root = path.resolve(__dirname, "..");
const publicRoot = path.join(root, "public");
const output = "/korean-skin-treatments/optimized";
const sources = [
  ...["review-scout", "review-scout-photo", "review-consultation", "review-content-studio", "review-compare", "review-creator", "review-questions"].map(name => `/korean-skin-treatments/review-guide-kr/${name}.png`),
  ...["consultation", "estimate-comparison"].map(name => `/korean-skin-treatments/upsell-kr/${name}.webp`),
  "/relyn_logo.png",
];

async function main() {
  await fs.mkdir(path.join(publicRoot, output), { recursive: true });
  const images = {}, audit = [];
  for (const source of sources) {
    const input = await fs.readFile(path.join(publicRoot, source));
    const metadata = await sharp(input).metadata();
    const logo = source === "/relyn_logo.png";
    const widths = logo ? [128, 256, 384] : [384, 768, 1152, Math.min(1536, metadata.width)];
    const variants = [];
    for (const width of [...new Set(widths.filter(w => w <= metadata.width))].sort((a, b) => a - b)) {
      const bytes = await sharp(input).rotate().resize({ width, withoutEnlargement: true })
        .webp({ quality: logo ? 90 : 75, alphaQuality: 100, effort: 6 }).toBuffer();
      const hash = createHash("sha256").update(bytes).digest("hex").slice(0, 10);
      const src = `${output}/${path.parse(source).name}-${width}-${hash}.webp`;
      await fs.writeFile(path.join(publicRoot, src), bytes);
      variants.push({ src, width, bytes: bytes.length });
    }
    images[source] = { width: metadata.width, height: metadata.height,
      variants: variants.map(({ src, width }) => ({ src, width })) };
    audit.push({ source, originalBytes: input.length, variants });
  }
  const shared = path.join(root, "app/korean-skin-treatments/shared");
  await fs.mkdir(shared, { recursive: true });
  await fs.writeFile(path.join(shared, "image-manifest.ts"),
    "// Generated by scripts/optimize-skin-guide-images.cjs. Do not edit by hand.\n" +
    "export const guideImages: Record<string, { width: number; height: number; variants: { src: string; width: number }[] }> = " + JSON.stringify(images, null, 2) + ";\n");
  await fs.writeFile(path.join(root, "scripts/skin-guide-image-audit.json"), JSON.stringify(audit, null, 2) + "\n");
  for (const item of audit) console.log(`${item.source}: ${item.originalBytes} bytes -> ${item.variants.map(v => `${v.width}w ${v.bytes} bytes`).join(", ")}`);
}
main().catch(error => { console.error(error); process.exitCode = 1; });
